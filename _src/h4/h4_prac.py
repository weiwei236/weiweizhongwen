def items(lst):
    out = []
    for it in lst:
        out.append([[w.split("：", 1)[0], w.split("：", 1)[1]] if "：" in w[:4] else ["", w] for w in it.split("|")])
    return out
def attach(B):
    for n, ps in PRAC.items():
        g = B[n]["grammar"]; assert len(g) == len(ps), n
        for p, (title, lst) in zip(g, ps):
            p["practice"] = [dict(type="fill", title=title, ref=True, items=items(lst))]
